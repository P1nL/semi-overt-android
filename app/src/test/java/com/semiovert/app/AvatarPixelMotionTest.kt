package com.semiovert.app

import com.semiovert.app.core.designsystem.AvatarPixelMotion
import org.junit.Assert.assertEquals
import org.junit.Test

class AvatarPixelMotionTest {
    @Test fun identitiesMixOnlyAfterTheSourceIsCoarseAndBeforeTheTargetResolves() {
        assertEquals(1f,AvatarPixelMotion.sourceClarity(0f),0f)
        assertEquals(0f,AvatarPixelMotion.identityMix(.39f),0f)
        for(p in listOf(.4f,.5f,.6f)) {
            assertEquals(0f,AvatarPixelMotion.sourceClarity(p),0f)
            assertEquals(0f,AvatarPixelMotion.targetClarity(p),0f)
        }
        assertEquals(.5f,AvatarPixelMotion.identityMix(.5f),.001f)
        assertEquals(1f,AvatarPixelMotion.identityMix(.61f),0f)
        assertEquals(.5f,AvatarPixelMotion.targetClarity(.8f),.001f)
        assertEquals(1f,AvatarPixelMotion.targetClarity(1f),.001f)
    }

    @Test fun resolutionsMatchValuesExecutedFromTheCurrentWebChoreography() {
        val progress=listOf(0f,.05f,.1f,.2f,.35f,.5f,.65f,.8f,.95f,.999f,1f)
        // Generated by importing pixelResolution from the sibling web checkout, not approximated easing.
        val expected=mapOf(
            32 to listOf(4,4,4,8,16,16,16,16,16,16,32),
            80 to listOf(4,4,8,16,32,32,64,64,64,64,80),
            116 to listOf(4,4,8,16,32,64,64,64,64,64,116),
            147 to listOf(4,4,8,16,32,64,64,128,128,128,147),
            305 to listOf(4,4,8,32,64,128,128,256,256,256,305),
        )
        for((size,cells) in expected) {
            assertEquals("Web pixelResolution at size=$size",cells,progress.map {AvatarPixelMotion.resolution(it,size)})
        }
    }

    @Test fun pixelDurationAndFadesMatchTheWebPixelStage() {
        assertEquals(750,AvatarPixelMotion.DURATION_MILLIS)
        assertEquals(.2f,AvatarPixelMotion.imageAlpha(0f),.0001f)
        assertEquals(1f,AvatarPixelMotion.imageAlpha(40f/750f),.0001f)
        assertEquals(1f,AvatarPixelMotion.outlineAlpha(500f/750f),.0001f)
        assertEquals(.5f,AvatarPixelMotion.outlineAlpha(625f/750f),.0001f)
        assertEquals(0f,AvatarPixelMotion.outlineAlpha(1f),.0001f)
    }
}
